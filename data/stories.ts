export const THEMES = [
  'all',
  'adventure',
  'kindness',
  'nature',
  'bedtime',
  'family',
  'courage',
] as const;

export type ThemeFilter = (typeof THEMES)[number];

export function getStoryById(id: string): Story | undefined {
  return STORIES.find((s) => s.id === id);
}

/** Deterministic "story of the day" so every parent sees the same pick on a given date. */
export function getStoryOfTheDay(date: Date = new Date()): Story {
  const start = new Date(date.getFullYear(), 0, 0);
  const dayOfYear = Math.floor((date.getTime() - start.getTime()) / 86_400_000);
  return STORIES[dayOfYear % STORIES.length];
}

export function formatAgeRange(story: Story): string {
  return `Ages ${story.ageMin}–${story.ageMax}`;
}
